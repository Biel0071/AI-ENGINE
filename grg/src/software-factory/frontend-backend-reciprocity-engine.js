'use strict';

/**
 * FÊNIX OS — Frontend-Backend Reciprocity Engine (Level 10)
 * =========================================================
 * Enforces the Supreme Constitutional Engineering Rule:
 * "NENHUMA FEATURE PODE EXISTIR EM APENAS UM LADO DO SISTEMA."
 * 
 * Capabilities:
 * 1. backendToFrontend(backendSpec):
 *    Produces reciprocal Frontend Contract, State Store, API Client, and UI Component markup.
 * 2. frontendToBackend(frontendSpec):
 *    Produces reciprocal Backend Route, Validation Schema, Service Handler, and DB Schema.
 * 3. verifyReciprocity(featureContract):
 *    Audits bidirectional integrity: Zero Orphaned Actions, Zero Orphaned Endpoints, Balanced State.
 */

class FrontendBackendReciprocityEngine {
  constructor(options = {}) {
    this.logger = options.logger || console;
    this.eventBus = options.eventBus || null;
  }

  /**
   * Generates reciprocal Frontend artifacts from a Backend specification
   * @param {object} backendSpec
   * @param {string} backendSpec.serviceName
   * @param {string} backendSpec.baseEndpoint
   * @param {Array<object>} backendSpec.routes - Array of { method, path, inputSchema, outputSchema, summary }
   */
  backendToFrontend(backendSpec) {
    if (!backendSpec || !backendSpec.serviceName) {
      throw new Error('backendSpec requires a serviceName');
    }

    const { serviceName, baseEndpoint = '/api/v2', routes = [] } = backendSpec;
    const pascalName = serviceName.charAt(0).toUpperCase() + serviceName.slice(1);
    const camelName = serviceName.charAt(0).toLowerCase() + serviceName.slice(1);

    // 1. Generate API Client methods
    const clientMethods = routes.map(r => {
      const methodName = `${r.method.toLowerCase()}${r.path.replace(/[^a-zA-Z0-9]/g, '_')}`;
      const url = `${baseEndpoint}${r.path}`;
      const hasBody = ['POST', 'PUT', 'PATCH'].includes(r.method.toUpperCase());
      const argList = hasBody ? 'payload = {}, options = {}' : 'params = {}, options = {}';
      const bodyOrQuery = hasBody ? 'body: JSON.stringify(payload),' : '';

      return `  async ${methodName}(${argList}) {
    const res = await fetch(\`${url}\`, {
      method: '${r.method.toUpperCase()}',
      headers: { 'Content-Type': 'application/json', ...(options.headers || {}) },
      ${bodyOrQuery}
    });
    if (!res.ok) throw new Error(\`Failed ${r.method.toUpperCase()} ${url}: \${res.statusText}\`);
    return await res.json();
  }`;
    }).join('\n\n');

    const apiClientCode = `// Autogenerated Reciprocal API Client for ${serviceName}
class ${pascalName}ApiClient {
${clientMethods}
}

module.exports = { ${pascalName}ApiClient };`;

    // 2. Generate State Management Store
    const stateStoreCode = `// Autogenerated Reactive State Store for ${serviceName}
class ${pascalName}StateStore {
  constructor(apiClient) {
    this.api = apiClient;
    this.data = null;
    this.loading = false;
    this.error = null;
    this.listeners = new Set();
  }

  subscribe(listener) {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  notify() {
    for (const fn of this.listeners) fn(this.getState());
  }

  getState() {
    return { data: this.data, loading: this.loading, error: this.error };
  }
}

module.exports = { ${pascalName}StateStore };`;

    // 3. Generate UI Component View Markup (Vanilla JS Canonical DOM)
    const uiMarkup = `<div id="view-${camelName}" class="fenix-capability-view hidden p-6">
  <div class="flex items-center justify-between mb-6">
    <h2 class="text-xl font-bold text-white tracking-wide">${pascalName} Operations</h2>
    <div id="${camelName}StatusBadge" class="px-3 py-1 rounded text-xs font-mono bg-cyan-950 text-cyan-400 border border-cyan-800">
      —
    </div>
  </div>
  <div class="grid grid-cols-1 md:grid-cols-2 gap-6">
    <div class="bg-slate-900 border border-slate-800 rounded-lg p-5">
      <h3 class="text-sm font-semibold text-slate-300 mb-4">Command Actions</h3>
      <div class="space-y-3" id="${camelName}ActionContainer">
${routes.map(r => `        <button type="button" data-action="${r.method.toLowerCase()}-${r.path}" class="w-full px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 text-sm font-medium rounded transition">
          ${r.summary || `${r.method.toUpperCase()} ${r.path}`}
        </button>`).join('\n')}
      </div>
    </div>
    <div class="bg-slate-900 border border-slate-800 rounded-lg p-5">
      <h3 class="text-sm font-semibold text-slate-300 mb-4">Live Telemetry & Output</h3>
      <pre id="${camelName}OutputConsole" class="bg-slate-950 p-4 rounded text-xs font-mono text-cyan-300 overflow-x-auto min-h-[160px]">—</pre>
    </div>
  </div>
</div>`;

    return {
      serviceName,
      reciprocalContracts: {
        apiClient: apiClientCode,
        stateStore: stateStoreCode,
        uiMarkup,
        totalRoutesBridged: routes.length
      },
      generatedAt: new Date().toISOString()
    };
  }

  /**
   * Generates reciprocal Backend artifacts from a Frontend specification
   * @param {object} frontendSpec
   * @param {string} frontendSpec.viewId
   * @param {string} frontendSpec.moduleName
   * @param {Array<object>} frontendSpec.actions - Array of { actionId, method, endpoint, payloadFields }
   */
  frontendToBackend(frontendSpec) {
    if (!frontendSpec || !frontendSpec.moduleName) {
      throw new Error('frontendSpec requires a moduleName');
    }

    const { moduleName, viewId = `view-${moduleName}`, actions = [] } = frontendSpec;
    const pascalName = moduleName.charAt(0).toUpperCase() + moduleName.slice(1);

    // 1. Generate Route Handlers
    const routeHandlers = actions.map(act => {
      const method = (act.method || 'POST').toLowerCase();
      const endpoint = act.endpoint || `/api/v2/${moduleName}/${act.actionId}`;

      return `  // Reciprocal route for ${viewId} action: ${act.actionId}
  router.${method}('${endpoint}', async (req, res) => {
    try {
      const payload = req.body || {};
      const result = await service.${act.actionId}(payload);
      return res.status(200).json({ status: 'success', data: result });
    } catch (err) {
      return res.status(500).json({ status: 'error', message: err.message });
    }
  });`;
    }).join('\n\n');

    const routerCode = `// Autogenerated Reciprocal Backend Router for ${moduleName}
function register${pascalName}Routes(router, service) {
${routeHandlers}
}

module.exports = { register${pascalName}Routes };`;

    // 2. Generate Service Handler Layer
    const serviceMethods = actions.map(act => {
      return `  async ${act.actionId}(payload) {
    // Validate input payload
    if (!payload) throw new Error('Missing request payload');
    
    // Execute core capability
    return {
      action: '${act.actionId}',
      processedAt: new Date().toISOString(),
      received: payload,
      success: true
    };
  }`;
    }).join('\n\n');

    const serviceCode = `// Autogenerated Reciprocal Service Layer for ${moduleName}
class ${pascalName}Service {
  constructor(storageManager) {
    this.storage = storageManager;
  }

${serviceMethods}
}

module.exports = { ${pascalName}Service };`;

    // 3. Generate Database Schema / Model definition
    const dbModelCode = `// Autogenerated Persistence Model for ${moduleName}
const ${pascalName}Schema = {
  tableName: 'fenix_${moduleName.toLowerCase()}_records',
  fields: {
    id: { type: 'UUID', primaryKey: true },
    actionId: { type: 'VARCHAR(64)', nullable: false },
    payload: { type: 'JSONB', nullable: true },
    result: { type: 'JSONB', nullable: true },
    createdAt: { type: 'TIMESTAMP', defaultValue: 'NOW()' }
  }
};

module.exports = { ${pascalName}Schema };`;

    return {
      moduleName,
      viewId,
      reciprocalContracts: {
        router: routerCode,
        service: serviceCode,
        dbModel: dbModelCode,
        totalActionsBridged: actions.length
      },
      generatedAt: new Date().toISOString()
    };
  }

  /**
   * Audits bidirectional reciprocity for a feature contract
   * Checks for orphaned buttons, dead endpoints, or asymmetric data paths.
   * @param {object} contract
   */
  verifyReciprocity(contract) {
    if (!contract) {
      throw new Error('Contract is required for reciprocity verification');
    }

    const {
      name = 'Unnamed Feature',
      frontendActions = [],
      backendRoutes = [],
      hasPersistence = true,
      hasTests = true
    } = contract;

    const actionEndpoints = new Set(frontendActions.map(a => `${(a.method || 'POST').toUpperCase()}:${a.endpoint || a.path}`));
    const routeEndpoints = new Set(backendRoutes.map(r => `${(r.method || 'GET').toUpperCase()}:${r.path || r.endpoint}`));

    const orphanedFrontendActions = frontendActions.filter(a => {
      const key = `${(a.method || 'POST').toUpperCase()}:${a.endpoint || a.path}`;
      return !routeEndpoints.has(key);
    });

    const orphanedBackendRoutes = backendRoutes.filter(r => {
      const key = `${(r.method || 'GET').toUpperCase()}:${r.path || r.endpoint}`;
      return !actionEndpoints.has(key);
    });

    const isFullyReciprocal = (orphanedFrontendActions.length === 0) &&
                              (orphanedBackendRoutes.length === 0) &&
                              hasPersistence &&
                              hasTests;

    const score = (
      (orphanedFrontendActions.length === 0 ? 0.3 : 0.1) +
      (orphanedBackendRoutes.length === 0 ? 0.3 : 0.1) +
      (hasPersistence ? 0.2 : 0.0) +
      (hasTests ? 0.2 : 0.0)
    );

    return {
      feature: name,
      isBalanced: isFullyReciprocal,
      reciprocityScore: Number(score.toFixed(2)),
      orphanedFrontendActions: orphanedFrontendActions.map(a => a.id || a.label || a.path),
      orphanedBackendRoutes: orphanedBackendRoutes.map(r => `${r.method} ${r.path || r.endpoint}`),
      hasPersistence,
      hasTests,
      status: isFullyReciprocal ? 'BALANCED' : 'UNBALANCED',
      checkedAt: new Date().toISOString()
    };
  }
}

module.exports = { FrontendBackendReciprocityEngine };
